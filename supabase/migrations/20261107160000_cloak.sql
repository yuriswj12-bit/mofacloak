-- Server-only portal data. No browser or anonymous API access.
BEGIN;
CREATE SCHEMA IF NOT EXISTS cloak;
REVOKE ALL ON SCHEMA cloak FROM PUBLIC;
DO $$ BEGIN
  IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='cloak_app') THEN
    CREATE ROLE cloak_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END $$;
CREATE TABLE cloak.accounts(id text PRIMARY KEY,name text NOT NULL,access_hash text UNIQUE NOT NULL,enabled integer NOT NULL DEFAULT 1 CHECK(enabled IN(0,1)),created_at bigint NOT NULL);
CREATE TABLE cloak.sessions(token_hash text PRIMARY KEY,account_id text NOT NULL REFERENCES cloak.accounts(id),expires_at bigint NOT NULL);
CREATE TABLE cloak.orders(
 id text PRIMARY KEY,account_id text NOT NULL REFERENCES cloak.accounts(id),idempotency_key text NOT NULL,request_fingerprint text NOT NULL,
 name text NOT NULL,plan_id text NOT NULL,kind text NOT NULL CHECK(kind IN('plan','gift')),cycle text NOT NULL CHECK(cycle IN('month','year')),
 months integer NOT NULL CHECK(months IN(1,12)),amount_cents integer NOT NULL CHECK(amount_cents>1),pid text NOT NULL,
 status text NOT NULL CHECK(status IN('creating','review','pending','paid','expired','failed')),
 trade_id text,payment_url text,actual_amount text,receive_address text,expires_at bigint,paid_trade_id text UNIQUE,tx_hash text,paid_at bigint,
 created_at bigint NOT NULL,updated_at bigint NOT NULL,currency text NOT NULL DEFAULT 'CNY' CHECK(currency IN('CNY','USD')),
 UNIQUE(account_id,idempotency_key));
CREATE UNIQUE INDEX orders_paid_chain_tx_unique ON cloak.orders(lower(tx_hash)) WHERE status='paid' AND tx_hash IS NOT NULL;
CREATE INDEX orders_account_created ON cloak.orders(account_id,created_at DESC);
CREATE TABLE cloak.payment_events(order_id text PRIMARY KEY REFERENCES cloak.orders(id),payload_digest text NOT NULL,created_at bigint NOT NULL);
CREATE TABLE cloak.fulfillment_jobs(order_id text PRIMARY KEY REFERENCES cloak.orders(id),account_id text NOT NULL REFERENCES cloak.accounts(id),plan_id text NOT NULL,months integer NOT NULL,status text NOT NULL DEFAULT 'pending',created_at bigint NOT NULL);
CREATE TABLE cloak.gifts(id text PRIMARY KEY,order_id text UNIQUE NOT NULL REFERENCES cloak.orders(id),owner_id text NOT NULL REFERENCES cloak.accounts(id),code text UNIQUE NOT NULL,plan_id text NOT NULL,name text NOT NULL,months integer NOT NULL,redeemed_by text REFERENCES cloak.accounts(id),redeemed_at bigint,created_at bigint NOT NULL);
CREATE TABLE cloak.tickets(id text PRIMARY KEY,account_id text NOT NULL REFERENCES cloak.accounts(id),title text NOT NULL,category text NOT NULL,status text NOT NULL CHECK(status IN('open','answered','closed')),request_key text NOT NULL,request_hash text NOT NULL,created_at bigint NOT NULL,updated_at bigint NOT NULL,UNIQUE(account_id,request_key));
CREATE TABLE cloak.ticket_messages(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ticket_id text NOT NULL REFERENCES cloak.tickets(id),author_role text NOT NULL CHECK(author_role IN('customer','support')),body text NOT NULL,request_key text NOT NULL,request_hash text NOT NULL,created_at bigint NOT NULL,UNIQUE(ticket_id,author_role,request_key));
CREATE INDEX tickets_account_updated ON cloak.tickets(account_id,updated_at DESC);
GRANT USAGE ON SCHEMA cloak TO cloak_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA cloak TO cloak_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA cloak TO cloak_app;
DO $$ DECLARE t record; r text; BEGIN
 FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='cloak' LOOP
  EXECUTE format('ALTER TABLE cloak.%I ENABLE ROW LEVEL SECURITY',t.tablename);
  EXECUTE format('REVOKE ALL ON TABLE cloak.%I FROM PUBLIC',t.tablename);
  EXECUTE format('CREATE POLICY server_only ON cloak.%I TO cloak_app USING(true) WITH CHECK(true)',t.tablename);
 END LOOP;
 FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
  IF EXISTS(SELECT FROM pg_roles WHERE rolname=r) THEN
   EXECUTE format('REVOKE ALL ON SCHEMA cloak FROM %I',r);
   EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA cloak FROM %I',r);
   EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA cloak FROM %I',r);
  END IF;
 END LOOP;
END $$;
COMMIT;
